import math, rwrd
def _sun():
    cx, cy, r1, r2 = 225, 48, 14, 30
    pts = []
    for i in range(48):
        a = math.pi * 2 * i / 48
        r = r2 if i % 2 == 0 else r1 + 3
        pts.append(f'{cx + r * math.cos(a):.1f},{cy + r * math.sin(a):.1f}')
    return f'<polygon points="{" ".join(pts)}" fill="#E5BE01"/><circle cx="{cx}" cy="{cy}" r="{r1}" fill="#E5BE01" stroke="#00A1DE" stroke-width="1.5"/>'
FLAG = '<svg class="flag" viewBox="0 0 300 200" role="img" aria-label="르완다 국기"><rect width="300" height="200" fill="#20603D"/><rect width="300" height="150" fill="#FAD201"/><rect width="300" height="100" fill="#00A1DE"/>' + _sun() + '</svg>'
def L(lo, rd=None):
    if rd is None: rd = rwrd.reading(lo)
    return f'<span class="lo">{lo}</span>' + (f' <span class="r">{rd}</span>' if rd else '')
def facts(rows): return '<table class="facts">' + ''.join(f'<tr><th>{a}</th><td>{b}</td></tr>' for a, b in rows) + '</table>'
def terms(rows): return '<div class="terms">' + ''.join(f'<div>{L(r[0])}<span class="m">{r[-1]}</span></div>' for r in rows) + '</div>'
def fig(inner, cap): return f'<figure>{inner}<figcaption>{cap}</figcaption></figure>'
def photo(key, cap): return f'@@PHOTO:{key}:{cap}@@'
def h3(t): return f'<h3>{t}</h3>'
def p(t): return f'<p>{t}</p>'
def top(left, right): return f'<div class="top2"><div>{left}</div><div>{right}</div></div>'
def two(a, b): return f'<div class="two"><div>{a}</div><div>{b}</div></div>'
def page(left, fr, a, b, tm=None, th='알아 둘 말'):
    return top(left, facts(fr)) + two(a, b) + ((h3(th) + terms(tm)) if tm else '')

