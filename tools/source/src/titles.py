# 묶음 옮기기 (앱 ID 기준, 옛 번호 -> 새 번호). 앱은 외운 기록을 새 번호로 옮긴다 (kbd_patch.py).
MOVE = {'4-02-01': ('P4-F', '4-07-04'), '6-01-09': ('P2-B', '6-02-10'), '6-04-04': ('P2-B', '6-02-11'), '6-04-05': ('P2-B', '6-02-12')}
IDMAP = {k: v[1] for k, v in MOVE.items()}
IDMAP.update({'6-01-%02d' % n: '6-01-%02d' % (n - 1) for n in range(10, 30)})
def move(DATA, BLAB):
    import re
    R = re.compile(r'(?<![\d\-])(\d-\d{2}-\d{2})(?![\d\-])')
    def rn(x):
        if isinstance(x, str): return R.sub(lambda m: IDMAP.get(m.group(1), m.group(1)), x)
        if isinstance(x, list): return [rn(y) for y in x]
        if isinstance(x, dict): return {rn(k): rn(v) for k, v in x.items()}
        return x
    subs = {s['id']: s for p in DATA['P'] for s in p['subs']}
    for old, (sid, new) in MOVE.items():
        src = [s for s in subs.values() if old in s['b']]; assert len(src) == 1, old
        src[0]['b'].remove(old); subs[sid]['b'].append(old)
    D, L = rn(DATA), rn(BLAB)
    assert len(D['B']) == len(DATA['B']) and len(L) == len(BLAB)
    for p in D['P']:
        for s in p['subs']: s['b'].sort()
    return D, L
